EDITED = ["specs/arena_a02.json", "test_prop_species.py", "CHANGELOG.md"]


def sha(b):
    return hashlib.sha256(b).hexdigest()[:16]


def one_hunk(old, new):
    """``(old_text, new_text)``: the one window of lines where ``old`` and ``new`` differ, widened by context lines
    until the old text occurs exactly once in ``old``."""
    a, b = old.splitlines(keepends=True), new.splitlines(keepends=True)
    ops = [op for op in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes() if op[0] != "equal"]
    assert ops, "no change"
    i1, i2, j1, j2 = ops[0][1], ops[-1][2], ops[0][3], ops[-1][4]
    ctx = 0
    while True:
        lo, hi = max(0, i1 - ctx), min(len(a), i2 + ctx)
        o = "".join(a[lo:hi])
        if o and old.count(o) == 1:
            break
        ctx += 1
        assert ctx < 40, "no unique anchor"
    n = "".join(b[j1 - (i1 - lo):j2 + (hi - i2)])
    return o, n


pins, plans = {}, {}
for name in EDITED:
    real = (DC / name).read_bytes()
    assert b"\r\n" not in real, name
    assert real == (STEP1 / name).read_bytes(), "deli_counter/%s is not the first patch's result" % name
    want = (CLONE / name).read_bytes()
    assert b"\r\n" not in want, name
    old_t, new_t = real.decode("utf-8"), want.decode("utf-8")
    o, n = one_hunk(old_t, new_t)
    assert old_t.replace(o, n) == new_t, "%s: the hunk does not reproduce the clone's file" % name
    pins[name] = sha(real)
    plans[name] = (o, n)
    print(name, "pinned", pins[name], "one hunk,", len(o), "->", len(n), "chars")

