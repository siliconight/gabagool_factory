TRANSPOSED = """    return [r0[0], r1[0], r2[0], origin[0],
            r0[1], r1[1], r2[1], origin[1],
            r0[2], r1[2], r2[2], origin[2]]"""

ROW_MAJOR = """    return [r0[0], r0[1], r0[2], origin[0],
            r1[0], r1[1], r1[2], origin[1],
            r2[0], r2[1], r2[2], origin[2]]"""


def _load(source: str):
    ns: dict = {}
    exec(compile(source, "<dressing_scene>", "exec"), ns)
    return ns


def _claims(ns) -> list:
    """The three properties the fix is FOR. Returns the names that hold.

    Each is stated at a yaw whose sine is not zero, which is the property the
    tests it replaces lacked -- at yaw 0 a transposed basis is the same basis.
    """
    held = []
    gt, mmf, t3d = (ns["godot_transform"], ns["multimesh_floats"],
                    ns["transform3d_string"])

    # 1. site +X under yaw r lands on Godot (cos r, 0, -sin r), which is
    #    basis COLUMN 0, read down the rows.
    r = 0.7
    r0, r1, r2, _o = gt((0, 0, 0), r)
    col0 = (r0[0], r1[0], r2[0])
    want = (math.cos(r), 0.0, -math.sin(r))
    if all(abs(a - b) < 1e-12 for a, b in zip(col0, want)):
        held.append("column0")

    # 2. the two off-diagonals carry opposite signs, so they swap under a
    #    transpose.
    yaw = 0.6
    r0, r1, r2, o = gt((0.0, 0.0, 0.0), yaw)
    f = mmf(r0, r1, r2, o)
    if (abs(f[2] - math.sin(yaw)) < 1e-12
            and abs(f[8] + math.sin(yaw)) < 1e-12):
        held.append("offdiagonals")

    # 3. buffer and literal describe the same transform, position by position.
    r0, r1, r2, o = gt((3.0, -4.0, 0.25), 0.9, scale=1.7)
    f = mmf(r0, r1, r2, o)
    lit = t3d(r0, r1, r2, o)
    n = [float(x) for x in lit[len("Transform3D("):-1].split(", ")]
    basis = f[0:3] + f[4:7] + f[8:11]
    if all(abs(a - b) <= 1e-5 * max(1.0, abs(b))
           for a, b in zip(basis, n[0:9])):
        held.append("agreement")
    return held


def _selftest() -> int:
    bad = 0
    src = _decode(MODULE_B64).decode("utf-8")
    tests = _decode(TESTS_B64).decode("utf-8")

    # -- payload integrity ---------------------------------------------------
    for name, data, post, n in (
            ("module", _decode(MODULE_B64), MODULE_POST, MODULE_POST_BYTES),
            ("tests", _decode(TESTS_B64), TESTS_POST, TESTS_POST_BYTES)):
        ok = _sha(data) == post and len(data) == n
        print(f"[selftest] {name} payload {len(data):,} bytes "
              f"sha {_sha(data)[:12]} {'ok' if ok else 'MISMATCH'}")
        bad |= 0 if ok else 1

    # -- the fix holds -------------------------------------------------------
    held = _claims(_load(src))
    print(f"[selftest] fixed module holds: {', '.join(held) or 'NOTHING'}")
    if len(held) != 3:
        print("[selftest] FAIL: the fixed module does not satisfy its own "
              "claims")
        bad = 1

    # -- FALSIFICATION: put the transpose back, the claims must break --------
    if src.count(ROW_MAJOR) != 1:
        print("[selftest] FAIL: cannot locate the row-major return to "
              "falsify -- the selftest is stale, treat the result as unknown")
        return 1
    broken = _claims(_load(src.replace(ROW_MAJOR, TRANSPOSED, 1)))
    print(f"[selftest] transposed module holds: "
          f"{', '.join(broken) or 'nothing'}")
    if broken != ["column0"]:
        print("[selftest] FAIL: with the transpose reinstated the buffer "
              "claims still pass. They are not testing the buffer.")
        bad = 1
    else:
        print("[selftest] falsified: reinstating the transpose breaks "
              "offdiagonals and agreement, and leaves column0 -- which reads "
              "godot_transform, not the buffer, so it should survive")

    # -- the naming that caused it is gone, checked by AST not by grep -------
    tree = ast.parse(src)
    ids = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}
    ids |= {a.arg for fn in ast.walk(tree)
            if isinstance(fn, ast.FunctionDef) for a in fn.args.args}
    stale = sorted(ids & {"bx", "by", "bz"})
    print(f"[selftest] basis-vector identifiers in code: {stale or 'none'}")
    if stale:
        print("[selftest] FAIL: the name that caused the transpose is still "
              "a live identifier")
        bad = 1

    # -- the sorted() comparison is gone from the test that needed order -----
    ttree = ast.parse(tests)
    target = "test_the_buffer_and_the_literal_describe_the_same_transform"
    fn = next((f for f in ast.walk(ttree)
               if isinstance(f, ast.FunctionDef) and f.name == target), None)
    if fn is None:
        print(f"[selftest] FAIL: {target} is not in the test payload")
        bad = 1
    else:
        sorts = [c for c in ast.walk(fn) if isinstance(c, ast.Call)
                 and isinstance(c.func, ast.Name) and c.func.id == "sorted"]
        print(f"[selftest] sorted() calls inside {target}: {len(sorts)}")
        if sorts:
            print("[selftest] FAIL: sorting discards the ordering, which is "
                  "the only thing this test exists to check")
            bad = 1

    print("[selftest] " + ("PASS" if not bad else "FAILED"))
    return bad


TARGETS = (MODULE, TESTS, VERSION_FILE, CHANGELOG)


