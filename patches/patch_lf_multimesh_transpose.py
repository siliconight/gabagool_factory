def _decode(payload: str) -> bytes:
    return base64.b64decode("".join(payload.split()))


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _replace(path: Path, payload: str, pre: str, post: str, *, check: bool) -> int:
    """Whole-file replacement, refusing on any drift from the recorded pre-image."""
    raw = path.read_bytes()
    got = _sha(raw)
    data = _decode(payload)
    if _sha(data) != post:
        print(f"REFUSING: {path.name} payload does not match its recorded "
              f"post_sha -- this script is corrupt, not your tree")
        return 1
    if got == post:
        print(f"  already applied  {path.name}")
        return 0
    if got != pre:
        print(f"REFUSING: {path.name} is not the file this patch was built "
              f"against.\n    expected sha {pre[:12]}  ({len(raw):,} bytes on "
              f"disk)\n    found    sha {got[:12]}")
        return 1
    if check:
        print(f"  would patch  {path.name}  {len(raw):,} -> {len(data):,} "
              f"({len(data) - len(raw):+,})")
        return 0
    side = path.with_suffix(path.suffix + SIDECAR)
    if not side.is_file():
        side.write_bytes(raw)
    path.write_bytes(data)
    print(f"  patched      {path.name}  {len(raw):,} -> {len(data):,} bytes "
          f"({len(data) - len(raw):+,})  sha {_sha(data)[:12]}")
    return 0


def _bump_version(path: Path, *, check: bool) -> int:
    raw = path.read_bytes()
    text = raw.decode("utf-8")
    if text.strip() == NEW_VERSION:
        print("  already applied  VERSION")
        return 0
    if text.strip() != OLD_VERSION:
        print(f"REFUSING: VERSION is {text.strip()!r}, expected {OLD_VERSION!r}")
        return 1
    data = text.replace(OLD_VERSION, NEW_VERSION, 1).encode("utf-8")
    if check:
        print(f"  would patch  VERSION  {OLD_VERSION} -> {NEW_VERSION}")
        return 0
    side = path.with_suffix(path.suffix + SIDECAR)
    if not side.is_file():
        side.write_bytes(raw)
    path.write_bytes(data)
    print(f"  patched      VERSION  {OLD_VERSION} -> {NEW_VERSION} "
          f"({len(raw)} -> {len(data)} bytes)")
    return 0


