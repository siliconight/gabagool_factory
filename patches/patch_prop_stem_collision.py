def _load(src, name):
    mod = types.ModuleType(name)
    mod.__dict__["__name__"] = name
    exec(compile(src, f"<{name}>", "exec"), mod.__dict__)
    return mod


def _kit_stems(kit, slots):
    out = []
    for s in slots:
        fit = s.get("fit", {}); dims = fit["dims"]
        typ = kit.slot_typename(s.get("role"), s.get("size_mod"))
        exact = typ != "wallEnd"
        w = int(round(dims[0] * 100)) if exact else None
        d = (int(round(dims[1] * 100))
             if exact and typ in kit.PLATE_ROLES + kit.VOLUME_ROLES else None)
        h = (int(round(dims[2] * 100))
             if exact and typ in kit.VOLUME_ROLES else None)
        out.append(kit.module_stem(typ, "delco", 1, w, None, d, None, None, h))
    return out


def _selftest() -> int:
    bad = 0
    for name, data, post, n in (
            ("kit", _decode(KIT_B64), KIT_POST, KIT_BYTES),
            ("themed_tscn", _decode(TT_B64), TT_POST, TT_BYTES),
            ("tests", _decode(TESTS_B64), TESTS_POST, TESTS_BYTES)):
        ok = _sha(data) == post and len(data) == n
        print(f"[selftest] {name} payload {len(data):,} bytes "
              f"sha {_sha(data)[:12]} {'ok' if ok else 'MISMATCH'}")
        bad |= 0 if ok else 1

    kit_src = _decode(KIT_B64).decode("utf-8")
    kit = _load(kit_src, "kit_probe")

    # THE MIRROR. themed_tscn imports tscn_export for transform maths this
    # selftest never touches, so it is stubbed rather than vendored.
    sys.modules.setdefault("tscn_export", types.ModuleType("tscn_export"))
    sys.modules["tscn_export"]._godot_transform = lambda *a, **k: None
    sys.modules["tscn_export"]._ref_path = lambda *a, **k: ""
    tt = _load(_decode(TT_B64).decode("utf-8"), "tt_probe")

    mine = _kit_stems(kit, FIXTURE)
    theirs = [tt.resolve_themed_stem(s, "delco", 1)[0] for s in FIXTURE]
    same = mine == theirs
    print(f"[selftest] zoo and deli_counter agree on all "
          f"{len(FIXTURE)} fixture slots: {same}")
    if not same:
        for a, b in zip(mine, theirs):
            if a != b:
                print(f"           zoo {a!r} != dc {b!r}")
        bad = 1

    # the defect itself
    collide = len(set(mine[:2])) == 1 or len(set(mine[2:4])) == 1
    print(f"[selftest] the two real colliding pairs now differ: {not collide}")
    if collide:
        bad = 1
    print(f"[selftest] a wall filename is untouched: {mine[4]!r}")
    if mine[4] != "wall_delco_01_w200":
        bad = 1
    print(f"[selftest] wallEnd is still a unit module: {mine[5]!r}")
    if mine[5] != "wallEnd_delco_01":
        bad = 1
    print(f"[selftest] a plate gains no height key: {mine[6]!r}")
    if mine[6] != "floor_delco_01_w4400_d2400":
        bad = 1

    # FALSIFICATION -- drop the height key; the height-only pair must re-collide
    marker = '    if height_cm is not None:\n        base += f"_h{int(round(height_cm))}"\n'
    if kit_src.count(marker) != 1:
        print("[selftest] FAIL: cannot locate the height key to falsify")
        return 1
    broken = _load(kit_src.replace(marker, "", 1), "kit_broken")
    b_mine = _kit_stems(broken, FIXTURE)
    recollided = len(set(b_mine[2:4])) == 1
    print(f"[selftest] falsified: without the height key the height-only pair "
          f"collides again: {recollided}")
    if not recollided:
        print("[selftest] FAIL: removing the height key changed nothing")
        bad = 1

    print("[selftest] " + ("PASS" if not bad else "FAILED"))
    return bad


TARGETS = (KIT, TESTS, ZOO_VERSION, ZOO_CHANGELOG, TT, DC_VERSION, DC_CHANGELOG)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--revert", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args(argv)
    if args.selftest:
        return _selftest()

    root = Path.cwd()
    missing = [t for t in TARGETS if t != TESTS and not (root / t).is_file()]
    if missing:
        print("cannot find " + ", ".join(missing)
              + "\n  -- run from the factory root (the directory holding zoo/)")
        return 1

    if args.revert:
        bad = 0
        for rel in TARGETS:
            p = root / rel
            side = p.with_suffix(p.suffix + SIDECAR)
            if side.is_file():
                p.write_bytes(side.read_bytes()); print(f"  reverted     {rel}")
            elif rel == TESTS and p.is_file():
                p.unlink(); print(f"  removed      {rel}  (this patch made it)")
            else:
                print(f"  no sidecar for {rel}"); bad = 1
        return bad

    def sweep(check):
        b = _replace(root / KIT, KIT_B64, KIT_PRE, KIT_POST, check=check)
        b |= _replace(root / TT, TT_B64, TT_PRE, TT_POST, check=check)
        b |= _create(root / TESTS, TESTS_B64, TESTS_POST, check=check)
        b |= _bump(root / ZOO_VERSION, ZOO_OLD, ZOO_NEW, check=check)
        b |= _bump(root / DC_VERSION, DC_OLD, DC_NEW, check=check)
        b |= _insert(root / ZOO_CHANGELOG, ZOO_SECTION, ZOO_ANCHOR,
                     after=True, check=check)
        b |= _insert(root / DC_CHANGELOG, DC_SECTION, DC_ANCHOR,
                     after=False, check=check)
        return b

    # SEVEN targets across TWO repos. Nothing is written until all seven say
    # they can be -- half of this patch is worse than none of it, because the
    # two module_stem mirrors would disagree and every prop would go missing.
    if sweep(check=True):
        print("\n  Nothing was written. Fix the drift above and re-run.")
        return 1
    if args.check:
        return 0
    if sweep(check=False):
        print("\n  PARTIAL APPLICATION -- the dry run passed and a write "
              "failed. Check the sidecars; the mirrors may disagree.")
        return 1
    print()
    print("  Verify:  python patches/patch_prop_stem_collision.py --selftest")
    print("           cd zoo; python -m pytest tests -q")
    print("           cd deli_counter; python -m pytest -q")
    print()
    print("  Then REBUILD the prop modules: existing prop GLBs no longer")
    print("  resolve and fall back to greybox until they are rebuilt.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
