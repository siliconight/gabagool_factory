def _decode(p): return base64.b64decode("".join(p.split()))
def _sha(b): return hashlib.sha256(b).hexdigest()


def _replace(path, payload, pre, post, *, check):
    raw = path.read_bytes(); got = _sha(raw); data = _decode(payload)
    if _sha(data) != post:
        print(f"REFUSING: {path.name} payload != recorded post_sha"); return 1
    if got == post:
        print(f"  already applied  {path.name}"); return 0
    if got != pre:
        print(f"REFUSING: {path.name} is not the file this was built against.\n"
              f"    expected {pre[:12]}  found {got[:12]} ({len(raw):,} bytes)")
        return 1
    if check:
        print(f"  would patch  {path.name}  {len(raw):,} -> {len(data):,}"); return 0
    side = path.with_suffix(path.suffix + SIDECAR)
    if not side.is_file(): side.write_bytes(raw)
    path.write_bytes(data)
    print(f"  patched      {path.name}  {len(raw):,} -> {len(data):,}  sha {_sha(data)[:12]}")
    return 0


def _create(path, payload, post, *, check):
    data = _decode(payload)
    if _sha(data) != post:
        print(f"REFUSING: {path.name} payload != post_sha"); return 1
    if path.is_file():
        if _sha(path.read_bytes()) == post:
            print(f"  already applied  {path.name}"); return 0
        print(f"REFUSING: {path} exists with different content"); return 1
    if check:
        print(f"  would create {path.name}  ({len(data):,} bytes)"); return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    print(f"  created      {path.name}  {len(data):,} bytes")
    return 0


def _bump(path, old, new, *, check):
    raw = path.read_bytes(); text = raw.decode("utf-8")
    if new in text:
        print(f"  already applied  {path.parent.name}/VERSION"); return 0
    if old not in text:
        print(f"REFUSING: {path} does not contain {old!r}"); return 1
    if check:
        print(f"  would patch  {path.parent.name}/VERSION  {old} -> {new}"); return 0
    side = path.with_suffix(path.suffix + SIDECAR)
    if not side.is_file(): side.write_bytes(raw)
    path.write_bytes(text.replace(old, new, 1).encode("utf-8"))
    print(f"  patched      {path.parent.name}/VERSION  {old} -> {new}")
    return 0


def _insert(path, section, anchor, *, after, check):
    """Put `section` before `anchor`, or straight after it when `after`."""
    raw = path.read_bytes(); text = raw.decode("utf-8")
    nl = "\r\n" if "\r\n" in text[:4000] else "\n"
    sec = section.replace("\n", nl)
    if sec in text:
        print(f"  already applied  {path.parent.name}/CHANGELOG.md"); return 0
    a = anchor.replace("\n", nl)
    if a not in text:
        print(f"REFUSING: {path} lacks its anchor {anchor.strip()!r}"); return 1
    if after:
        i = text.index(a) + len(a)
        while text[i:i + len(nl)] == nl:
            i += len(nl)
        out = text[:i] + sec + text[i:]
    else:
        if not text.startswith(a):
            print(f"REFUSING: {path} does not START with its anchor"); return 1
        out = sec + text
    data = out.encode("utf-8")
    if check:
        print(f"  would patch  {path.parent.name}/CHANGELOG.md  "
              f"{len(raw):,} -> {len(data):,}"); return 0
    side = path.with_suffix(path.suffix + SIDECAR)
    if not side.is_file(): side.write_bytes(raw)
    path.write_bytes(data)
    print(f"  patched      {path.parent.name}/CHANGELOG.md  {len(raw):,} -> {len(data):,}")
    return 0


