def repo_root(start=None):
    d = os.path.abspath(start or os.path.dirname(os.path.abspath(__file__)))
    for _ in range(8):
        if (os.path.isdir(os.path.join(d, "zoo", "zoo_keeper"))
                and os.path.isdir(os.path.join(d, "tools"))):
            return d
        nd = os.path.dirname(d)
        if nd == d:
            break
        d = nd
    return None


def sha(b):
    return hashlib.sha256(b).hexdigest()


def rd(p):
    with open(p, "rb") as fh:
        return fh.read()


def wr(p, b):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "wb") as fh:
        fh.write(b)


def plan(root):
    rows, ok = [], True
    for rel, d in PAYLOAD.items():
        p = os.path.join(root, rel.replace("/", os.sep))
        if not os.path.isfile(p):
            rows.append((rel, "MISSING - refusing", False))
            ok = False
            continue
        cur = sha(rd(p))
        if cur == d["post_sha"]:
            rows.append((rel, "already-current", True))
        elif cur == d["pre_sha"]:
            rows.append((rel, f"replace {d['pre_bytes']} -> {d['post_bytes']} B",
                         True))
        else:
            rows.append((rel, f"DRIFT sha {cur[:12]} != {d['pre_sha'][:12]} "
                              "(is patch_dressing_shape.py applied?)", False))
            ok = False
    return ok, rows


def show(rows):
    w = max(len(r[0]) for r in rows)
    for rel, msg, good in rows:
        print(f"  {'ok ' if good else 'STOP'}  {rel:<{w}}  {msg}")


def apply(root):
    ok, rows = plan(root)
    show(rows)
    if not ok:
        print("\nREFUSING: nothing written. Resolve the lines marked STOP.")
        return 1
    n = 0
    for rel, d in PAYLOAD.items():
        p = os.path.join(root, rel.replace("/", os.sep))
        cur = rd(p)
        if sha(cur) == d["post_sha"]:
            continue
        side = p + SIDECAR
        if not os.path.exists(side):
            wr(side, cur)
        wr(p, base64.b64decode(d["b64"]))
        assert sha(rd(p)) == d["post_sha"], rel
        n += 1
    print(f"\nWROTE {n} file(s). Sidecars: *{SIDECAR}")
    print("Next, in this order, and read each before running the next:")
    print("  python tools/shape_metrics.py --selftest")
    print("  pwsh -ExecutionPolicy Bypass -File zoo\\tools\\preview_dressing.ps1")
    print("The WARN should be gone and open_edges should read 0 on all four.")
    return 0


def revert(root):
    n = 0
    for rel in PAYLOAD:
        p = os.path.join(root, rel.replace("/", os.sep))
        side = p + SIDECAR
        if os.path.exists(side):
            wr(p, rd(side))
            os.remove(side)
            print(f"  reverted {rel}")
            n += 1
    print(f"reverted {n} file(s)")
    return 0


def selftest():
    bad = 0

    def fail(msg):
        nonlocal bad
        print(f"  FAIL  {msg}")
        bad += 1

    print("patch_shape_metrics_02 selftest")

    for rel, d in PAYLOAD.items():
        b = base64.b64decode(d["b64"])
        if sha(b) != d["post_sha"] or len(b) != d["post_bytes"]:
            fail(f"payload {rel} does not match its recorded hash/size")
    print(f"  ok    {len(PAYLOAD)} payloads decode to their recorded hashes")

    # Every genome payload must be valid JSON, must declare tris_lod0, must NOT
    # still declare tris_max, and must carry a budget that is actually a
    # positive number -- renaming a key to one the validator reads is pointless
    # if the value behind it is zero or missing.
    import json
    seen = 0
    for rel, d in PAYLOAD.items():
        if not rel.endswith(".json"):
            continue
        seen += 1
        g = json.loads(base64.b64decode(d["b64"]).decode("utf-8"))
        b = g.get("budgets", {})
        if "tris_max" in b:
            fail(f"{rel} still declares tris_max")
        if not isinstance(b.get("tris_lod0"), int) or b["tris_lod0"] <= 0:
            fail(f"{rel} has no positive tris_lod0 budget: {b}")
    print(f"  ok    {seen} genomes declare a positive tris_lod0 and no tris_max")

    # FALSIFICATION: the rename must be the ONLY change. Renaming the key back
    # on the post-image has to reproduce the pre-image byte for byte; if it
    # does not, this patch is quietly reformatting genomes it was only meant
    # to rename a key in. (That very thing happened while writing it: a
    # json.dump round-trip silently rewrote dress_cover.json from 1725 to 1621
    # bytes, and this assertion is what would have caught it.)
    root = repo_root()
    for rel, d in PAYLOAD.items():
        if not rel.endswith(".json"):
            continue
        post = base64.b64decode(d["b64"]).decode("utf-8")
        back = post.replace('"tris_lod0"', '"tris_max"').encode("utf-8")
        if len(back) != d["pre_bytes"]:
            fail(f"{rel}: undoing the rename does not restore the byte count "
                 f"({len(back)} != {d['pre_bytes']}) - something else changed")
        elif root:
            p = os.path.join(root, rel.replace("/", os.sep))
            if os.path.isfile(p) and sha(rd(p)) == d["pre_sha"] \
                    and sha(back) != d["pre_sha"]:
                fail(f"{rel}: undoing the rename does not restore the file")
    print("  ok    undoing the rename restores each genome byte for byte")

    ref = base64.b64decode(next(iter(PAYLOAD.values()))["b64"])
    mut = bytearray(ref)
    mut[len(mut) // 2] ^= 0x20
    if sha(bytes(mut)) == sha(ref):
        fail("a mutated payload hashed identically")
    else:
        print("  ok    one flipped byte changes the hash")

    print("SELFTEST", "PASSED" if bad == 0 else f"FAILED ({bad})")
    return 1 if bad else 0


def main(argv):
    if "--selftest" in argv:
        return selftest()
    root = None
    if "--root" in argv:
        root = os.path.abspath(argv[argv.index("--root") + 1])
    root = root or repo_root()
    if not root:
        print("Could not find the gabagool_factory root. Pass --root <path>.")
        return 2
    print(f"repo root: {root}")
    if "--revert" in argv:
        return revert(root)
    ok, rows = plan(root)
    if "--check" in argv:
        show(rows)
        print("\n--check only: nothing written."
              + ("" if ok else "  RESOLVE THE STOP LINES FIRST."))
        return 0 if ok else 1
    return apply(root)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
