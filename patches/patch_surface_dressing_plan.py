def repo_root(start=None):
    d = os.path.abspath(start or os.path.dirname(os.path.abspath(__file__)))
    for _ in range(8):
        if (os.path.isdir(os.path.join(d, "patina"))
                and os.path.isfile(os.path.join(d, "patina", "patina",
                                                "determinism.py"))):
            return d
        nd = os.path.dirname(d)
        if nd == d:
            break
        d = nd
    return None


def sha(b):
    return hashlib.sha256(b).hexdigest()


def rd(p):
    with open(p, "rb") as fh:
        return fh.read()


def wr(p, b):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "wb") as fh:
        fh.write(b)


def plan(root):
    rows, ok = [], True
    for rel, d in PAYLOAD.items():
        p = os.path.join(root, rel.replace("/", os.sep))
        exists = os.path.isfile(p)
        if d["kind"] == "new":
            if exists and sha(rd(p)) == d["post_sha"]:
                rows.append((rel, "already-current", True))
            elif exists:
                rows.append((rel, "EXISTS AND DIFFERS - refusing", False))
                ok = False
            else:
                rows.append((rel, f"create {d['post_bytes']} B", True))
            continue
        if not exists:
            rows.append((rel, "MISSING - refusing", False))
            ok = False
            continue
        cur = sha(rd(p))
        if cur == d["post_sha"]:
            rows.append((rel, "already-current", True))
        elif cur == d["pre_sha"]:
            rows.append((rel, f"replace {d['pre_bytes']} -> {d['post_bytes']} B",
                         True))
        else:
            rows.append((rel, f"DRIFT sha {cur[:12]} != {d['pre_sha'][:12]}",
                         False))
            ok = False
    return ok, rows


def show(rows):
    w = max(len(r[0]) for r in rows)
    for rel, msg, good in rows:
        print(f"  {'ok ' if good else 'STOP'}  {rel:<{w}}  {msg}")


def apply(root):
    ok, rows = plan(root)
    show(rows)
    if not ok:
        print("\nREFUSING: nothing written. Resolve the lines marked STOP.")
        return 1
    n = 0
    for rel, d in PAYLOAD.items():
        p = os.path.join(root, rel.replace("/", os.sep))
        if os.path.isfile(p):
            cur = rd(p)
            if sha(cur) == d["post_sha"]:
                continue
            side = p + SIDECAR
            if not os.path.exists(side):
                wr(side, cur)
        wr(p, base64.b64decode(d["b64"]))
        assert sha(rd(p)) == d["post_sha"], rel
        n += 1
    print(f"\nWROTE {n} file(s). Sidecars: *{SIDECAR}")
    print("Next:")
    print("  cd patina")
    print("  python -m pytest tests/test_surface_dressing.py -q")
    print("  python -m pytest tests -q")
    print("33 new tests. Nothing existing imports surface_dressing yet, so")
    print("the rest of the Patina suite should be exactly as you left it.")
    return 0


def revert(root):
    n = 0
    for rel, d in PAYLOAD.items():
        p = os.path.join(root, rel.replace("/", os.sep))
        side = p + SIDECAR
        if os.path.exists(side):
            wr(p, rd(side))
            os.remove(side)
            print(f"  reverted {rel}")
            n += 1
        elif d["kind"] == "new" and os.path.isfile(p):
            if sha(rd(p)) == d["post_sha"]:
                os.remove(p)
                print(f"  removed  {rel} (this patch created it)")
                n += 1
            else:
                print(f"  KEPT     {rel} (modified since; not ours to delete)")
    print(f"reverted {n} file(s)")
    return 0


def selftest():
    bad = 0

    def fail(msg):
        nonlocal bad
        print(f"  FAIL  {msg}")
        bad += 1

    print("patch_surface_dressing_plan selftest")

    for rel, d in PAYLOAD.items():
        b = base64.b64decode(d["b64"])
        if sha(b) != d["post_sha"] or len(b) != d["post_bytes"]:
            fail(f"payload {rel} does not match its recorded hash/size")
    print(f"  ok    {len(PAYLOAD)} payloads decode to their recorded hashes")

    import ast

    def src(rel):
        return base64.b64decode(PAYLOAD[rel]["b64"]).decode("utf-8")

    mod = src("patina/patina/surface_dressing.py")
    tst = src("patina/tests/test_surface_dressing.py")
    tree = ast.parse(mod)

    funcs = {n.name for n in tree.body if isinstance(n, ast.FunctionDef)}
    for want in ("plan", "audit", "catalogue_entry", "coverage_by_zone",
                 "zone_for", "excluded", "band_of"):
        if want not in funcs:
            fail(f"surface_dressing has no {want}()")
    print("  ok    plan / audit / catalogue_entry are all present")

    # FALSIFICATION: the honesty number must be BORROWED from the capsule
    # block, not written down. A copy does not move when the capsule does.
    copied = [n.value for n in ast.walk(tree)
              if isinstance(n, ast.Constant) and isinstance(n.value, float)
              and 0.11 < n.value < 0.125]
    if copied:
        fail(f"the step limit is hard-coded {copied} -- it must come from "
             "surfaces['capsule']['unassisted_step_max_m']")
    if "unassisted_step_max_m" not in mod:
        fail("the plan never reads unassisted_step_max_m from the capsule")
    print("  ok    the step limit is read from the capsule, not copied")

    # Both cost budgets must exist as parameters of plan(), or the 46.8M
    # measurement in the header is a story rather than a fixed bug.
    plan_fn = next(n for n in tree.body
                   if isinstance(n, ast.FunctionDef) and n.name == "plan")
    kwargs = {a.arg for a in plan_fn.args.args + plan_fn.args.kwonlyargs}
    for want in ("instance_budget", "tri_budget", "surfaces", "catalogue"):
        if want not in kwargs:
            fail(f"plan() has no {want} parameter")
    print("  ok    plan() takes both an instance and a triangle budget")

    # A catalogue entry without a triangle count cannot be costed.
    ce = next(n for n in tree.body
              if isinstance(n, ast.FunctionDef) and n.name == "catalogue_entry")
    if "tris" not in {a.arg for a in ce.args.args + ce.args.kwonlyargs}:
        fail("catalogue_entry does not require a triangle count")
    print("  ok    an asset cannot enter the catalogue without a cost")

    for code in ("CODE_TOO_TALL", "CODE_BUDGET", "CODE_EXCLUDED",
                 "CODE_TRI_BUDGET", "CODE_INSTANCE_BUDGET", "CODE_UNBOUNDED"):
        if code not in mod:
            fail(f"{code} is missing; a refusal with no code cannot be read")
    print("  ok    every refusal has a code")

    # The three regressions must be pinned by tests, not merely fixed.
    for needle, what in (
            ("test_budget_is_shared_by_area_not_by_zone_count",
             "the per-zone cap that made density depend on how the site was "
             "chopped up"),
            ("test_causes_are_not_all_the_same_value",
             "the anchor-cause table shadowing the exposure lookup"),
            ("test_an_unbounded_plan_is_enormous_and_says_so",
             "the 46.8M-triangle unbounded plan")):
        if needle not in tst:
            fail(f"no test pins {what}")
    print("  ok    all three pre-ship regressions are pinned by named tests")

    # And audit() must recompute rather than trust the planner.
    if "coverage_by_zone" not in mod or "recomputes" not in tst:
        fail("nothing checks that audit sums the orders instead of reading a "
             "stored total")
    print("  ok    audit recomputes coverage from the orders")

    # Byte comparison, not text. patina/VERSION is CRLF and the first draft
    # of this patch rewrote it as LF -- a silent line-ending change on a file
    # whose only real content is a version number, which is precisely the kind
    # of thing a diff review skims past.
    raw = base64.b64decode(PAYLOAD["patina/VERSION"]["b64"])
    if raw != b"Patina 0.20.0\r\n":
        fail(f"VERSION payload bytes are {raw!r}; the file is CRLF and must "
             "stay CRLF")
    ver = src("patina/VERSION").strip()
    vpy = src("patina/patina/version.py")
    if ver != "Patina 0.20.0":
        fail(f"VERSION payload is {ver!r}")
    if '__version__ = "0.20.0"' not in vpy:
        fail("version.py and VERSION disagree")
    ch = src("patina/CHANGELOG.md")
    if "## [0.20.0]" not in ch or "## [0.19.0]" not in ch:
        fail("CHANGELOG payload is not 0.20.0 on top of 0.19.0")
    print("  ok    VERSION, version.py and CHANGELOG all say 0.20.0")

    ref = base64.b64decode(next(iter(PAYLOAD.values()))["b64"])
    mut = bytearray(ref)
    mut[len(mut) // 2] ^= 0x20
    if sha(bytes(mut)) == sha(ref):
        fail("a mutated payload hashed identically")
    else:
        print("  ok    one flipped byte changes the hash")

    print("SELFTEST", "PASSED" if bad == 0 else f"FAILED ({bad})")
    return 1 if bad else 0


