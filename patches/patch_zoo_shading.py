CHANGELOG_SECTION = """\
## [0.40.0] - Zoo shades its geometry

Every mesh Zoo has ever built was flat-shaded. `bm_to_object` ran bevel ->
recalc normals -> UV -> wear and stopped; there is no `shade_smooth`, no
auto-smooth and no weighted-normal step anywhere in `bpylayer`. So a
14-segment water tank read as a dodecagon and every bevel bought geometry
without buying shading, which is most of what a bevel is for.

### Added
- **`geometry.shade_by_angle(bm, angle_deg=SMOOTH_ANGLE_DEG)`** -- smooth
  shading with hard creases, decided per edge from the geometry: smooth every
  face, then mark an edge sharp when its two faces disagree by more than the
  threshold. Called from `bm_to_object` after `recalc_face_normals` (it reads
  face normals) and before the UV projection (which does not care).

- **`SMOOTH_ANGLE_DEG = 50.0`, and the number is arithmetic rather than
  taste.** `bevel_edges` runs `segments=1`, so a chamfer on a 90-degree corner
  meets each neighbour at exactly 45 degrees. The usual hard-surface default
  of 30 would have marked every chamfer sharp and this whole change would have
  done nothing. 50 sits above 45 and well below 90, so:

      fold                                smooth?
      coplanar                    0 deg   yes
      24-segment wheel side      15 deg   yes
      14-segment cylinder      25.7 deg   yes
      10-segment cylinder        36 deg   yes
      1-segment chamfer          45 deg   yes
      just over threshold        51 deg   no
      box corner                 90 deg   no
      boundary edge (1 face)         --   no

  Every one of those was checked against the function before it shipped.

### Why this is safe to apply to all 57 species at once
- **Triangle count is unchanged.** Nothing here adds a face, so
  `validate.evaluate`'s `budgets.tris_lod0` check is untouched. The exported
  VERTEX count usually falls, because smooth shading lets a corner share one
  normal where flat shading needed three.
- **Blender 4.1 removed `mesh.use_auto_smooth`** and replaced it with an
  operator that adds a Smooth-by-Angle modifier. Zoo builds headless,
  deterministically, with no operators and no modifier stack, so neither was
  available. Doing it on the bmesh needs neither and bakes into the export.
- A boundary or non-manifold edge is left hard. There is no second face to
  average with, and smoothing against a normal that is not there is how you
  get a seam that looks like a crack.

### Changed
- `tools/preview_street_solids.ps1` picks up a Pixelcoat pack from
  `zoo/_skins` when one exists, matching `preview_floor_ceiling.ps1`, and says
  so when it does not. **There is no `_skins` directory in this tree**, so
  every preview so far -- dressing included -- has been flat style colour plus
  baked vertex wear, judging silhouette and shading alone. Worth knowing before
  judging an asset.

### Not done
- **Weighted normals.** The modifier weights a corner normal by face area so a
  narrow bevel strip stops dominating. There is no bmesh equivalent, and adding
  a modifier stack to a build that has deliberately avoided one is a bigger
  decision than this. With `segments=1` bevels the overlap with correct
  sharp-edge marking is large; revisit if bevels ever go multi-segment.
- **Bevel segments stay at 1.** Two would give a rounder roll-off and roughly
  double bevel geometry, against budgets that are already checked and were
  already exceeded once by a pebble.

"""


def _decode(p): return base64.b64decode("".join(p.split()))
def _sha(b): return hashlib.sha256(b).hexdigest()


def _replace(path, payload, pre, post, *, check):
    raw = path.read_bytes(); got = _sha(raw); data = _decode(payload)
    if _sha(data) != post:
        print(f"REFUSING: {path.name} payload != recorded post_sha"); return 1
    if got == post:
        print(f"  already applied  {path.name}"); return 0
    if got != pre:
        print(f"REFUSING: {path.name} is not the file this was built against.\n"
              f"    expected {pre[:12]}  found {got[:12]} ({len(raw):,} bytes)")
        return 1
    if check:
        print(f"  would patch  {path.name}  {len(raw):,} -> {len(data):,}"); return 0
    side = path.with_suffix(path.suffix + SIDECAR)
    if not side.is_file(): side.write_bytes(raw)
    path.write_bytes(data)
    print(f"  patched      {path.name}  {len(raw):,} -> {len(data):,}")
    return 0


def _bump(path, *, check):
    raw = path.read_bytes(); text = raw.decode("utf-8")
    if NEW_VERSION in text:
        print("  already applied  VERSION"); return 0
    if OLD_VERSION not in text:
        print(f"REFUSING: zoo/VERSION reads {text.strip()!r}, "
              f"expected {OLD_VERSION!r}"); return 1
    if check:
        print(f"  would patch  VERSION  {OLD_VERSION} -> {NEW_VERSION}"); return 0
    side = path.with_suffix(path.suffix + SIDECAR)
    if not side.is_file(): side.write_bytes(raw)
    path.write_bytes(text.replace(OLD_VERSION, NEW_VERSION, 1).encode("utf-8"))
    print(f"  patched      VERSION  {OLD_VERSION} -> {NEW_VERSION}")
    return 0


def _insert(path, *, check):
    raw = path.read_bytes(); text = raw.decode("utf-8")
    nl = "\r\n" if "\r\n" in text[:4000] else "\n"
    sec = CHANGELOG_SECTION.replace("\n", nl)
    if sec in text:
        print("  already applied  CHANGELOG.md"); return 0
    anchor = CHANGELOG_ANCHOR.replace("\n", nl)
    if not text.startswith(anchor):
        print("REFUSING: CHANGELOG.md does not start with '# Changelog'"); return 1
    i = len(anchor)
    while text[i:i + len(nl)] == nl:
        i += len(nl)
    data = (text[:i] + sec + text[i:]).encode("utf-8")
    if check:
        print(f"  would patch  CHANGELOG.md  {len(raw):,} -> {len(data):,}"); return 0
    side = path.with_suffix(path.suffix + SIDECAR)
    if not side.is_file(): side.write_bytes(raw)
    path.write_bytes(data)
    print(f"  patched      CHANGELOG.md  {len(raw):,} -> {len(data):,}")
    return 0


# --- selftest ---------------------------------------------------------------
#
# `shade_by_angle` is pure geometry -- it reads face normals and sets flags --
# so it is liftable out of a module that imports bpy and bmesh, and testable
# without either. That is the whole reason to check the arithmetic here rather
# than discover it in a render.

class _V:
    def __init__(self, *c): self.c = c
    def dot(self, o): return sum(a * b for a, b in zip(self.c, o.c))


class _F:
    def __init__(self, n): self.normal, self.smooth = n, False


class _E:
    def __init__(self, faces): self.link_faces, self.smooth = faces, True


class _BM:
    def __init__(self, faces, edges): self.faces, self.edges = faces, edges
    def normal_update(self): pass


def _lift(src, angle_override=None):
    """Pull `shade_by_angle` + its constant out of the module source."""
    tree = ast.parse(src)
    fn = next((n for n in tree.body if isinstance(n, ast.FunctionDef)
               and n.name == "shade_by_angle"), None)
    const = next((n for n in tree.body if isinstance(n, ast.Assign)
                  and getattr(n.targets[0], "id", "") == "SMOOTH_ANGLE_DEG"),
                 None)
    if fn is None or const is None:
        return None, None
    if angle_override is not None:
        const.value = ast.Constant(value=float(angle_override))
    ns = {"math": math}
    mod = ast.fix_missing_locations(ast.Module(body=[const, fn],
                                               type_ignores=[]))
    exec(compile(mod, "<lifted>", "exec"), ns)
    return ns["shade_by_angle"], ns["SMOOTH_ANGLE_DEG"]


def _fold(deg):
    r = math.radians(deg)
    return _F(_V(0, 0, 1)), _F(_V(math.sin(r), 0, math.cos(r)))


def _smooths(fn, deg):
    a, b = _fold(deg)
    e = _E([a, b])
    fn(_BM([a, b], [e]))
    return e.smooth


CASES = [("coplanar", 0.0, True), ("24-seg wheel", 15.0, True),
         ("14-seg cylinder", 360 / 14, True), ("10-seg cylinder", 36.0, True),
         ("1-seg chamfer", 45.0, True), ("just under", 49.0, True),
         ("just over", 51.0, False), ("box corner", 90.0, False)]


def _selftest() -> int:
    bad = 0
    for name, data, post, n in (
            ("geometry", _decode(GEOMETRY_B64), GEOMETRY_POST, GEOMETRY_BYTES),
            ("preview", _decode(PREVIEW_B64), PREVIEW_POST, PREVIEW_BYTES)):
        ok = _sha(data) == post and len(data) == n
        print(f"[selftest] {name} payload {len(data):,} bytes "
              f"sha {_sha(data)[:12]} {'ok' if ok else 'MISMATCH'}")
        bad |= 0 if ok else 1

    src = _decode(GEOMETRY_B64).decode("utf-8")
    fn, angle = _lift(src)
    if fn is None:
        print("[selftest] FAIL: shade_by_angle is not in the payload")
        return 1
    print(f"[selftest] SMOOTH_ANGLE_DEG = {angle}")
    if not 45.0 < angle < 90.0:
        print("[selftest] FAIL: the threshold must sit above the 45-degree "
              "chamfer a segments=1 bevel makes and below a 90-degree corner")
        bad = 1

    for label, deg, want in CASES:
        got = _smooths(fn, deg)
        mark = "" if got == want else "   <-- WRONG"
        print(f"[selftest]   {label:<16} {deg:>6.1f} deg  "
              f"smooth={str(got):<5}{mark}")
        if got != want:
            bad = 1

    # a boundary edge has no second face; leaving it hard is the honest answer
    a = _F(_V(0, 0, 1)); e = _E([a]); fn(_BM([a], [e]))
    print(f"[selftest]   boundary edge          smooth={e.smooth}")
    if e.smooth is not False:
        bad = 1
    print(f"[selftest]   faces marked smooth    {a.smooth}")
    if not a.smooth:
        bad = 1

    # FALSIFICATION: the usual 30-degree default would mark the chamfer sharp,
    # and the entire change would be invisible.
    fn30, _ = _lift(src, angle_override=30.0)
    chamfer_at_30 = _smooths(fn30, 45.0)
    print(f"[selftest] falsified: at the usual 30-degree default the 45-degree "
          f"chamfer smooths = {chamfer_at_30} (must be False)")
    if chamfer_at_30:
        print("[selftest] FAIL: the threshold is not doing the work the "
              "docstring claims for it")
        bad = 1

    # and it must actually be CALLED
    called = "shade_by_angle(bm)" in src
    print(f"[selftest] bm_to_object calls shade_by_angle: {called}")
    if not called:
        print("[selftest] FAIL: a shading function nothing calls is a no-op")
        bad = 1

    print("[selftest] " + ("PASS" if not bad else "FAILED"))
    return bad


TARGETS = (GEOMETRY, PREVIEW, VERSION_FILE, CHANGELOG)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--revert", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args(argv)
    if args.selftest:
        return _selftest()

    root = Path.cwd()
    for rel in TARGETS:
        if not (root / rel).is_file():
            print(f"cannot find {rel} -- run from the factory root"
                  + ("\n  (preview_street_solids.ps1 comes from "
                     "patch_zoo_street_preview.py; apply that first)"
                     if rel == PREVIEW else ""))
            return 1

    if args.revert:
        bad = 0
        for rel in TARGETS:
            p = root / rel
            side = p.with_suffix(p.suffix + SIDECAR)
            if side.is_file():
                p.write_bytes(side.read_bytes()); print(f"  reverted     {rel}")
            else:
                print(f"  no sidecar for {rel}"); bad = 1
        return bad

    def sweep(check):
        b = _replace(root / GEOMETRY, GEOMETRY_B64, GEOMETRY_PRE,
                     GEOMETRY_POST, check=check)
        b |= _replace(root / PREVIEW, PREVIEW_B64, PREVIEW_PRE, PREVIEW_POST,
                      check=check)
        b |= _bump(root / VERSION_FILE, check=check)
        b |= _insert(root / CHANGELOG, check=check)
        return b

    if sweep(check=True):
        print("\n  Nothing was written. Fix the drift above and re-run.")
        return 1
    if args.check:
        return 0
    if sweep(check=False):
        print("\n  PARTIAL APPLICATION -- check the sidecars.")
        return 1
    print()
    print("  Re-render:  pwsh -File zoo\\tools\\preview_street_solids.ps1")
    print()
    print("  EVERY species changes appearance, not just the street set.")
    print("  Triangle counts do not move; vertex counts usually fall.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
